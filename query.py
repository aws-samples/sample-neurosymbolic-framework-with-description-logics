"""Query CLI for ontology QA CLI."""
import sys
import argparse
from pathlib import Path

from ontology_qa_cli.config import load_config, resolve_ontology
from ontology_qa_cli.executor import execute_query_program


def parse_args() -> argparse.Namespace:
    """Parse Query CLI arguments.

    Arguments:
        program (required): Path to the query program.
        question (required): Natural language question.
        --ontology: Ontology name to resolve OWL file path.
        --config: Path to YAML config file (default: ontology_config.yaml).
    """
    parser = argparse.ArgumentParser(
        description="Execute a query program to answer a natural language question about an OWL ontology."
    )
    parser.add_argument(
        "program",
        type=Path,
        help="Path to the query program (generated by the Builder CLI).",
    )
    parser.add_argument(
        "question",
        type=str,
        help="Natural language question to answer about the ontology.",
    )
    parser.add_argument(
        "--ontology",
        type=str,
        default=None,
        help="Ontology name to resolve the OWL file path from the configuration.",
    )
    parser.add_argument(
        "--config",
        type=Path,
        default=Path("ontology_config.yaml"),
        help="Path to the YAML configuration file (default: ontology_config.yaml).",
    )
    return parser.parse_args()


def run_query(args: argparse.Namespace) -> None:
    """Execute the query program and print the answer."""
    # Expand ~ in path arguments
    args.program = args.program.expanduser()
    args.config = args.config.expanduser()

    program_path: Path = args.program
    question: str = args.question

    # Resolve OWL file path if ontology is specified
    if args.ontology:
        config = load_config(args.config)
        entry = resolve_ontology(config, args.ontology)
        onto_file = entry.owl_file
    else:
        # Without --ontology, we cannot resolve an OWL file path.
        # The query program must handle this itself; pass an empty path placeholder.
        print(
            "Error: --ontology is required to resolve the OWL file path.",
            file=sys.stderr,
        )
        sys.exit(1)

    # Execute the query program
    result = execute_query_program(program_path, onto_file, question)

    # Handle non-zero exit code
    if result.exit_code != 0:
        print(
            f"Error: Query program exited with code {result.exit_code}",
            file=sys.stderr,
        )
        if result.stderr:
            print(result.stderr, file=sys.stderr)
        sys.exit(1)

    # Handle missing Answer: format
    if result.answer is None:
        print(
            "Error: Query program output did not contain an answer in the expected 'Answer: <text>' format.",
            file=sys.stderr,
        )
        sys.exit(1)

    # Print the extracted answer to stdout
    print(result.answer)


def main() -> None:
    """CLI entry point."""
    args = parse_args()
    run_query(args)


if __name__ == "__main__":
    main()
