"""Program fixer using kiro-cli for ontology QA CLI."""
import logging
import re
import sys
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Optional
import subprocess
from textwrap import dedent

from ontology_qa_cli.judge import JudgmentResult

logger = logging.getLogger(__name__)


def _extract_credits(output: str) -> float:
    """Extract kiro credits from output like 'Credits: 2.90 • Time: 3m 20s'."""
    match = re.search(r"Credits:\s*([\d.]+)", output)
    if match:
        return float(match.group(1))
    return 0.0


@dataclass
class FixResult:
    success: bool
    modified_program: Optional[str]  # Source code if successful
    exit_code: int
    error_message: Optional[str]
    stdout: str = ""  # Captured kiro-cli stdout
    stderr: str = ""  # Captured kiro-cli stderr
    duration: float = 0.0  # Wall-clock seconds
    credits: float = 0.0  # Kiro credits used


def generate_task_file(
    failed_judgments: list,  # list[JudgmentResult]
    program_path: Path,
    ontology_file: Path = None,
) -> str:
    """Generate TASK.md content instructing kiro-cli to fix the program.

    Creates a markdown document listing each failed question with its
    question text, generated answer, expected answer, and LLM judge assessment.

    Args:
        failed_judgments: List of JudgmentResult objects for questions that were judged incorrect.
        program_path: Path to the query program file that needs fixing.
        ontology_file: Path to the OWL ontology file used by the program.

    Returns:
        The TASK.md content as a string.
    """
    lines = []
    lines.append("# Fix Query Program")
    lines.append("")

    ontology_note = ""
    if ontology_file:
        cache_file = ontology_file.with_suffix(".sqlite3")
        ontology_note = (
            f"\n\n    The ontology file is located at `{ontology_file}`. "
            "Note: this file is very large. Do NOT try to read the entire file. "
            "Instead, inspect small subsets (e.g. grep for specific class names, "
            "or read the first few hundred lines to understand the structure)."
            f"\n\n    IMPORTANT: A pre-built SQLite cache exists at `{cache_file}`. "
            "When you need to query the ontology interactively (e.g. to explore classes "
            "or test queries), use the SQLite cache for much faster loading:\n"
            "    ```python\n"
            "    import owlready2\n"
            f"    owlready2.default_world.set_backend(filename='{cache_file}')\n"
            f"    onto = owlready2.get_ontology('file://{ontology_file}').load()\n"
            "    ```\n"
            "    Do NOT load the raw .owl file directly — it takes too long."
        )

    lines.append(dedent(f"""\
        Fix the query program `{program_path}` based on the feedback below.
        The program is producing incorrect answers for the following questions.
        Modify the program so that it produces correct answers for these cases
        while maintaining correctness for other questions.{ontology_note}

        Some rules:
        - the program being evolved must be invoked with two positional
          command-line args: the path to the ontology file and the question
          being asked.
        - the program being evolved must output to stdout a line "Answer: ...."
          which is the answer generated by the program
        - the program can use an LLM to understand the question, and to
          compose an answer, but the core reasoning (the answering of the question)
          must be done by using owlready to interogate the ontology.
        - the answer generated by the program should not contain identifiers
          that are internal to the ontology, such as `fmaXXX`, as these mean
          nothing to the user.
        - format the answer as Markdown so it renders nicely in a chat UI.
          The answer begins at the "Answer: " stdout line and may span multiple
          lines after it, so you may use block Markdown — bulleted/numbered
          lists, tables, **bold**, `inline code`, headings — as well as inline
          emphasis. Everything printed from "Answer: " to the end of stdout is
          treated as the answer, so emit the answer LAST and keep any debug
          output above it.
    """))
    lines.append("")

    for i, judgment in enumerate(failed_judgments, start=1):
        lines.append(f"## Failed Question {i}")
        lines.append("")
        lines.append(f"**Question:** {judgment.question}")
        lines.append("")
        lines.append(f"**Generated Answer:** {judgment.generated_answer}")
        lines.append("")
        lines.append(f"**Expected Answer:** {judgment.expected_answer}")
        lines.append("")
        lines.append(f"**Assessment:** {judgment.assessment}")
        lines.append("")
        if judgment.stdout:
            lines.append("**Stdout:**")
            lines.append("```")
            lines.append(judgment.stdout.strip())
            lines.append("```")
            lines.append("")
        if judgment.stderr:
            lines.append("**Stderr:**")
            lines.append("```")
            lines.append(judgment.stderr.strip())
            lines.append("```")
            lines.append("")

    return "\n".join(lines)


def fix_program(
    current_program: str,
    failed_judgments: list,
    working_dir: Path,
    timeout: int = 1000,
    ontology_file: Path = None,
) -> FixResult:
    """Invoke kiro-cli to fix the query program based on judge feedback.

    Writes the program and TASK.md into working_dir, invokes kiro-cli there,
    and reads back the modified program.

    Args:
        current_program: The current source code of the query program.
        failed_judgments: List of JudgmentResult objects for failed questions.
        working_dir: Directory to use for the fix (e.g. the iteration directory).
        timeout: Timeout in seconds for kiro-cli.

    Returns:
        FixResult indicating success/failure and the modified program if successful.
    """
    working_dir.mkdir(parents=True, exist_ok=True)

    program_file = working_dir / "query_program.py"
    task_file = working_dir / "TASK.md"

    # Write the current program source
    program_file.write_text(current_program)

    # Generate and write the TASK.md
    task_content = generate_task_file(failed_judgments, Path("query_program.py"), ontology_file=ontology_file)
    task_file.write_text(task_content)

    kiro_prompt = "Read TASK.md in this directory and follow the guidance in there to fix query_program.py."
    logger.info("kiro-cli command prompt: %s", kiro_prompt)
    logger.info(
        "kiro-cli invocation: working_dir=%s, program=%d bytes, prompt=%d bytes, task_md=%d bytes",
        working_dir, len(current_program), len(kiro_prompt), len(task_content),
    )

    # Invoke kiro-cli with streaming output via pty for line-buffered output
    start_time = time.monotonic()
    BG_BLACK = "\033[40m\033[97m"
    BG_RED = "\033[41m\033[97m"
    RESET = "\033[0m"

    try:
        import pty
        import os
        import select
        import errno

        # Create a pty so kiro-cli thinks it's writing to a terminal (line-buffered)
        master_fd, slave_fd = pty.openpty()

        proc = subprocess.Popen(
            [
                "kiro-cli", "chat", "--no-interactive", "--trust-all-tools",
                kiro_prompt,
            ],
            cwd=str(working_dir),
            stdout=slave_fd,
            stderr=slave_fd,
            text=False,
        )
        os.close(slave_fd)  # Close slave in parent; child has it

        collected_output = []
        print(f"{BG_BLACK}--- kiro-cli output ---{RESET}")

        while True:
            # Check timeout
            elapsed = time.monotonic() - start_time
            if timeout is not None:
                remaining = timeout - elapsed
                if remaining <= 0:
                    proc.kill()
                    proc.wait()
                    os.close(master_fd)
                    error_msg = f"kiro-cli timed out after {elapsed:.1f}s (limit: {timeout}s)"
                    logger.error(error_msg)
                    print(f"\n{BG_RED}--- kiro-cli TIMED OUT ---{RESET}")
                    return FixResult(
                        success=False,
                        modified_program=None,
                        exit_code=-1,
                        error_message=error_msg,
                        stdout="".join(collected_output),
                        stderr="",
                        duration=elapsed,
                    )
                select_timeout = min(remaining, 0.5)
            else:
                select_timeout = 0.5

            ready, _, _ = select.select([master_fd], [], [], select_timeout)
            if ready:
                try:
                    data = os.read(master_fd, 4096)
                except OSError as e:
                    if e.errno == errno.EIO:
                        # Child closed the pty
                        break
                    raise
                if not data:
                    break
                text = data.decode("utf-8", errors="replace")
                collected_output.append(text)
                sys.stdout.write(text)
                sys.stdout.flush()
            elif proc.poll() is not None:
                # Process exited and no more data
                break

        os.close(master_fd)
        proc.wait()
        print(f"\n{BG_BLACK}--- end kiro-cli output ---{RESET}")

        full_stdout = "".join(collected_output)
        full_stderr = ""  # Combined into stdout via pty

    except FileNotFoundError:
        error_msg = "kiro-cli executable not found (expected at /usr/bin/kiro-cli)"
        logger.error(error_msg)
        return FixResult(
            success=False,
            modified_program=None,
            exit_code=-1,
            error_message=error_msg,
            duration=0.0,
        )

    elapsed = time.monotonic() - start_time
    logger.info("kiro-cli completed in %.1fs with exit code %d", elapsed, proc.returncode)

    if proc.returncode != 0:
        error_msg = (
            f"kiro-cli exited with code {proc.returncode}: "
            f"{full_stderr.strip() or full_stdout.strip()}"
        )
        logger.error(error_msg)
        return FixResult(
            success=False,
            modified_program=None,
            exit_code=proc.returncode,
            error_message=error_msg,
            stdout=full_stdout,
            stderr=full_stderr,
            duration=elapsed,
            credits=_extract_credits(full_stdout),
        )

    # Read back the modified program
    try:
        modified_program = program_file.read_text()
    except OSError as e:
        error_msg = f"Failed to read modified program: {e}"
        logger.error(error_msg)
        return FixResult(
            success=False,
            modified_program=None,
            exit_code=0,
            error_message=error_msg,
            stdout=full_stdout,
            stderr=full_stderr,
            duration=elapsed,
            credits=_extract_credits(full_stdout),
        )

    return FixResult(
        success=True,
        modified_program=modified_program,
        exit_code=0,
        error_message=None,
        stdout=full_stdout,
        stderr=full_stderr,
        duration=elapsed,
        credits=_extract_credits(full_stdout),
    )
